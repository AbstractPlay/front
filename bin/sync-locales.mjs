/* eslint-env node */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import { SUPPORTED_LANGUAGES } from "../src/lib/uiLanguages.js";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");

const FRONT_LOCALES = path.join(ROOT, "public", "locales");
const BUNDLE_LOCALES_EN = path.join(ROOT, "src", "locales", "en");
const GAMESLIB_LOCALES = path.join(
  ROOT,
  "node_modules",
  "@abstractplay",
  "gameslib",
  "locales",
);

const BUNDLED_EN_NAMESPACES = ["apfront", "apgames", "apresults"];
const TIME_AGO_LOCALE_DIR = path.join(
  ROOT,
  "node_modules",
  "javascript-time-ago",
  "locale",
);
const TIME_AGO_LOCALE_DATA_FILE = path.join(
  ROOT,
  "src",
  "lib",
  "timeAgoLocaleData.js",
);

function importAlias(code) {
  return code.replace(/-/g, "_");
}

function syncTimeAgoLocaleData() {
  const codes = [
    ...new Set(SUPPORTED_LANGUAGES.map((lang) => lang.timeAgoCode ?? lang.code)),
  ];
  const imports = [];
  const entries = [];

  for (const code of codes) {
    const localePath = path.join(TIME_AGO_LOCALE_DIR, `${code}.json`);
    if (!fs.existsSync(localePath)) {
      console.warn(
        `No javascript-time-ago locale for "${code}"; relative timestamps for that UI language will use English`,
      );
      continue;
    }
    const alias = importAlias(code);
    imports.push(
      `import ${alias} from "javascript-time-ago/locale/${code}.json";`,
    );
    entries.push(`  "${code}": ${alias},`);
  }

  const content = `/* eslint-disable -- auto-generated by bin/sync-locales.mjs */
${imports.join("\n")}

export const TIME_AGO_LOCALE_DATA_BY_FILE = {
${entries.join("\n")}
};
`;

  fs.writeFileSync(TIME_AGO_LOCALE_DATA_FILE, content, "utf8");
  console.log("Synced javascript-time-ago locale imports");
}

function copyLocaleTree(sourceRoot, namespaces) {
  if (!fs.existsSync(sourceRoot)) {
    console.warn(`Skipping missing locale source: ${sourceRoot}`);
    return;
  }

  for (const lang of fs.readdirSync(sourceRoot)) {
    const langDir = path.join(sourceRoot, lang);
    if (!fs.statSync(langDir).isDirectory()) {
      continue;
    }

    const targetLangDir = path.join(FRONT_LOCALES, lang);
    fs.mkdirSync(targetLangDir, { recursive: true });

    for (const file of fs.readdirSync(langDir)) {
      if (!file.endsWith(".json")) {
        continue;
      }
      const namespace = file.replace(/\.json$/, "");
      if (!namespaces.includes(namespace)) {
        continue;
      }
      fs.copyFileSync(path.join(langDir, file), path.join(targetLangDir, file));
    }
  }
}

function syncBundledEnglish() {
  fs.mkdirSync(BUNDLE_LOCALES_EN, { recursive: true });

  const missing = [];
  for (const ns of BUNDLED_EN_NAMESPACES) {
    const sourcePath = path.join(FRONT_LOCALES, "en", `${ns}.json`);
    if (!fs.existsSync(sourcePath)) {
      missing.push(sourcePath);
      continue;
    }
    fs.copyFileSync(sourcePath, path.join(BUNDLE_LOCALES_EN, `${ns}.json`));
  }

  if (missing.length > 0) {
    console.error("Missing English locale files required for bundled fallback:");
    for (const p of missing) {
      console.error(`  ${p}`);
    }
    process.exit(1);
  }

  console.log("Synced English locale files into src/locales/en for bundling");
}

fs.mkdirSync(FRONT_LOCALES, { recursive: true });
copyLocaleTree(GAMESLIB_LOCALES, ["apgames", "apresults"]);
console.log("Synced gameslib locale files into public/locales");
syncBundledEnglish();
syncTimeAgoLocaleData();
